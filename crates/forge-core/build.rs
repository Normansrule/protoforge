//! Build script: scans the module sources for dispatch arms like
//! `"dsp.fft" =>` and generates the method catalog served by `api.catalog`,
//! so the list of engine methods can never drift from the code.
use std::fs;
use std::path::Path;

fn walk(dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    let mut entries: Vec<_> = entries.flatten().collect();
    entries.sort_by_key(|e| e.path());
    for e in entries {
        let p = e.path();
        if p.is_dir() {
            walk(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") {
            println!("cargo:rerun-if-changed={}", p.display());
            let src = fs::read_to_string(&p).unwrap_or_default();
            scan(&src, out);
        }
    }
}

fn is_ident(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !s.chars().next().unwrap().is_ascii_digit()
}

fn scan(src: &str, out: &mut Vec<String>) {
    let b = src.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'"' {
            if let Some(len) = src[i + 1..].find('"') {
                let lit = &src[i + 1..i + 1 + len];
                let rest = src[i + 2 + len..].trim_start();
                if rest.starts_with("=>") {
                    if let Some((m, f)) = lit.split_once('.') {
                        if is_ident(m) && is_ident(f) && !out.iter().any(|x| x == lit) {
                            out.push(lit.to_string());
                        }
                    }
                }
                i += len + 2;
                continue;
            }
        }
        i += 1;
    }
}

fn main() {
    let mut methods = Vec::new();
    walk(Path::new("src"), &mut methods);
    methods.sort();
    let body: String = methods.iter().map(|m| format!("    \"{m}\",\n")).collect();
    let code =
        format!("/// Every `module.method` handled by a dispatcher (generated by build.rs).\npub const METHODS: &[&str] = &[\n{body}];\n");
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("catalog.rs");
    fs::write(out, code).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}
