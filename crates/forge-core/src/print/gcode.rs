//! Generic Marlin/Klipper-flavoured G-code writer.
//!
//! Absolute XYZ (`G90`), absolute (`M82`) or relative (`M83`) extrusion,
//! temperatures from `PrintParams` (`M104/M109` hot-end, `M140/M190` bed),
//! `G28` homing, a purge line along the front of the bed, part-cooling fan
//! (`M106`) switched on after the first layer, retraction on long travels,
//! and an end script that parks the head and switches heaters off.
//!
//! This is **generic** G-code for learning and for open firmware printers.
//! Bambu Lab printers expect their own sliced 3MF/G-code (Bambu Studio or
//! OrcaSlicer, with printer-specific start code, flow calibration and
//! AMS handling) — export the STL/3MF from the CAD Studio for those.
//!
//! References: RepRap wiki "G-code" (https://reprap.org/wiki/G-code);
//! Marlin G-code index (https://marlinfw.org/meta/gcode/).

use std::fmt::Write as _;

use super::motion::{e_per_mm, speed, SliceStats};
use super::slicer::{Kind, Layer, SliceSettings};
use crate::project::PrintParams;

pub fn write(layers: &[Layer], pp: &PrintParams, st: &SliceSettings, stats: &SliceStats, part: &str) -> String {
    let mut o = String::with_capacity(layers.len() * 40_000);
    let [cx, cy] = st.bed_center;
    let fx = |x: f64| x + cx;
    let fy = |y: f64| y + cy;
    let _ = writeln!(o, "; Generated by Protoforge Print Lab — generic Marlin/Klipper G-code");
    let _ = writeln!(
        o,
        "; For Bambu Lab printers use Bambu Studio / OrcaSlicer with the exported STL/3MF."
    );
    let _ = writeln!(o, "; part: {part}");
    let _ = writeln!(
        o,
        "; layers: {}  layer_height: {:.3} mm  first_layer: {:.3} mm",
        stats.layers, pp.layer_height_mm, st.first_layer_mm
    );
    let _ = writeln!(
        o,
        "; line_width: {:.3} mm  perimeters: {}  infill: {:.0}%",
        pp.line_width_mm, pp.perimeters, pp.infill_pct
    );
    let _ = writeln!(
        o,
        "; estimated time: {} ({:.0} s)  filament: {:.2} m / {:.2} g",
        stats.time_text, stats.time_s, stats.filament_m, stats.filament_g
    );
    let _ = writeln!(
        o,
        "; bed centre: X{cx:.1} Y{cy:.1}  nozzle: {:.2} mm  filament: {:.2} mm",
        pp.nozzle_mm, pp.filament_diameter_mm
    );
    let _ = writeln!(o, "M140 S{:.0} ; bed heat (no wait)", pp.bed_temp_c);
    let _ = writeln!(o, "M104 S{:.0} ; hot-end heat (no wait)", pp.nozzle_temp_c);
    let _ = writeln!(o, "G28 ; home all axes");
    let _ = writeln!(o, "M190 S{:.0} ; wait for bed", pp.bed_temp_c);
    let _ = writeln!(o, "M109 S{:.0} ; wait for hot-end", pp.nozzle_temp_c);
    let _ = writeln!(o, "G90 ; absolute XYZ");
    let _ = writeln!(
        o,
        "{}",
        if st.relative_e {
            "M83 ; relative extrusion"
        } else {
            "M82 ; absolute extrusion"
        }
    );
    let _ = writeln!(o, "G92 E0");
    let _ = writeln!(o, "M107 ; fan off");
    // Purge line along the front edge of the bed.
    let fil_area = std::f64::consts::PI * pp.filament_diameter_mm.powi(2) / 4.0;
    let purge_e = 0.3 * 0.8 * 100.0 / fil_area;
    let _ = writeln!(o, "G1 Z0.300 F600");
    let _ = writeln!(o, "G0 X5.000 Y5.000 F6000");
    let _ = writeln!(o, "G1 X105.000 Y5.000 E{purge_e:.5} F1200 ; purge line");
    let _ = writeln!(o, "G1 X105.000 Y5.400 F1200");
    let _ = writeln!(o, "G92 E0");
    let mut e = 0.0f64;
    let mut retracted = false;
    let rf = (st.retract_speed_mm_s * 60.0).round();
    for layer in layers {
        let _ = writeln!(o, ";LAYER:{} Z={:.3}", layer.index, layer.z);
        if layer.index == 1 {
            let _ = writeln!(o, "M106 S{:.0} ; part fan", (st.fan_pct / 100.0 * 255.0).clamp(0.0, 255.0));
        }
        let _ = writeln!(o, "G1 Z{:.3} F600", layer.z);
        let epm = e_per_mm(pp.line_width_mm, layer.height, pp.filament_diameter_mm);
        let mut last_kind: Option<Kind> = None;
        for p in &layer.paths {
            if p.kind == Kind::Travel {
                let to = p.pts[p.pts.len() - 1];
                if p.retract && st.retract_mm > 0.0 && !retracted {
                    if st.relative_e {
                        let _ = writeln!(o, "G1 E-{:.5} F{rf}", st.retract_mm);
                    } else {
                        let _ = writeln!(o, "G1 E{:.5} F{rf}", e - st.retract_mm);
                    }
                    retracted = true;
                }
                let f = (speed(Kind::Travel, layer.index, pp, st) * 60.0).round();
                let _ = writeln!(o, "G0 X{:.3} Y{:.3} F{f}", fx(to[0]), fy(to[1]));
                continue;
            }
            if retracted {
                if st.relative_e {
                    let _ = writeln!(o, "G1 E{:.5} F{rf}", st.retract_mm);
                } else {
                    let _ = writeln!(o, "G1 E{e:.5} F{rf}");
                }
                retracted = false;
            }
            if last_kind != Some(p.kind) {
                let _ = writeln!(o, ";TYPE:{}", p.kind.label());
                last_kind = Some(p.kind);
            }
            let f = (speed(p.kind, layer.index, pp, st) * 60.0).round();
            let mut first = true;
            for w in p.pts.windows(2) {
                let l = crate::cad::geom2d::dist(w[0], w[1]);
                if l < 1e-6 {
                    continue;
                }
                let de = l * epm;
                e += de;
                let ev = if st.relative_e { de } else { e };
                if first {
                    let _ = writeln!(o, "G1 X{:.3} Y{:.3} E{ev:.5} F{f}", fx(w[1][0]), fy(w[1][1]));
                    first = false;
                } else {
                    let _ = writeln!(o, "G1 X{:.3} Y{:.3} E{ev:.5}", fx(w[1][0]), fy(w[1][1]));
                }
            }
        }
    }
    let top = layers.last().map(|l| l.z).unwrap_or(0.0);
    let _ = writeln!(o, "; end");
    if !st.relative_e {
        let _ = writeln!(o, "G1 E{:.5} F{rf} ; retract", e - st.retract_mm.max(0.0));
    } else {
        let _ = writeln!(o, "G1 E-{:.5} F{rf} ; retract", st.retract_mm.max(0.0));
    }
    let _ = writeln!(o, "M104 S0 ; hot-end off");
    let _ = writeln!(o, "M140 S0 ; bed off");
    let _ = writeln!(o, "M107 ; fan off");
    let _ = writeln!(o, "G1 Z{:.3} F600 ; lift", (top + 10.0).min(250.0));
    let _ = writeln!(o, "G0 X5.000 Y{:.3} F6000 ; present the part", st.bed_size[1] - 10.0);
    let _ = writeln!(o, "M84 ; motors off");
    o
}

#[cfg(test)]
pub(crate) mod tests {
    /// Every non-comment line must be a well-formed command word followed
    /// by address words (letter + number).
    pub fn valid_line(line: &str) -> bool {
        let code = line.split(';').next().unwrap_or("").trim();
        if code.is_empty() {
            return true;
        }
        let mut words = code.split_whitespace();
        let cmd = words.next().unwrap();
        let (c, n) = cmd.split_at(1);
        if !matches!(c, "G" | "M" | "T") || n.parse::<u32>().is_err() {
            return false;
        }
        words.all(|w| {
            let (a, v) = w.split_at(1);
            a.chars().all(|ch| ch.is_ascii_uppercase()) && v.parse::<f64>().is_ok()
        })
    }
}
