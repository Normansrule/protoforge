/// Concatenate headers and sources into one translation unit for wokwi.com
/// (strip the local `#include "iris_*.h"` lines).
fn amalgamate(parts: &[(String, String)]) -> String {
    let mut s = String::new();
    let order = |n: &str| -> usize {
        if n.ends_with(".h") {
            0
        } else {
            1
        }
    };
    let mut sorted: Vec<&(String, String)> = parts.iter().collect();
    sorted.sort_by_key(|(n, _)| order(n));
    for (name, content) in sorted {
        s += &format!("\n/* ===================== {name} ===================== */\n");
        for line in content.lines() {
            if line.trim_start().starts_with("#include \"iris_") {
                continue;
            }
            s += line;
            s += "\n";
        }
    }
    s
}

