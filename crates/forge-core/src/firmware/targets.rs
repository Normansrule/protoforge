    /// Strip comments, string and character literals so brace counting sees only code.
    fn code_only(src: &str) -> String {
        let b = src.as_bytes();
        let mut out = String::with_capacity(src.len());
        let mut i = 0;
        while i < b.len() {
            if b[i] == b'/' && i + 1 < b.len() && b[i + 1] == b'*' {
                i += 2;
                while i + 1 < b.len() && !(b[i] == b'*' && b[i + 1] == b'/') {
                    i += 1;
                }
                i += 2;
            } else if b[i] == b'/' && i + 1 < b.len() && b[i + 1] == b'/' {
                while i < b.len() && b[i] != b'\n' {
                    i += 1;
                }
            } else if b[i] == b'"' || b[i] == b'\'' {
                let q = b[i];
                i += 1;
                while i < b.len() && b[i] != q {
                    if b[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
                i += 1;
            } else {
                out.push(b[i] as char);
                i += 1;
            }
        }
        out
    }

    fn balanced(src: &str) -> bool {
        let c = code_only(src);
        let mut stack = Vec::new();
        for ch in c.chars() {
            match ch {
                '{' | '(' | '[' => stack.push(ch),
                '}' | ')' | ']' => {
                    let o = stack.pop();
                    let ok = matches!((o, ch), (Some('{'), '}') | (Some('('), ')') | (Some('['), ']'));
                    if !ok {
                        return false;
                    }
                }
                _ => {}
            }
        }
        stack.is_empty()
    }

    fn inputs() -> Inputs {
        Inputs::from_project(&Project::iris(), &ble::LinkParams::default())
    }

    #[test]
    fn every_generated_c_file_is_balanced() {
        let i = inputs();
        for files in [xiao_project(&i), esp32_project(&i), zephyr_project(&i)] {
            for f in files {
                if [".c", ".h", ".ino", ".overlay"].iter().any(|e| f.path.ends_with(e)) {
                    assert!(balanced(&f.content), "unbalanced brackets in {}", f.path);
                }
            }
        }
    }

    #[test]
