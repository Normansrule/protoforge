//! Complete firmware projects for the three targets:
//!
//! * `xiao_arduino` — Seeed Studio XIAO nRF52840 Sense, Arduino (Seeed's
//!   Adafruit-based nRF52 core: `bluefruit.h`, `PDM.h`), U8g2, PlatformIO.
//! * `esp32s3_wokwi` — ESP32-S3-DevKitC-1 + MPU-6050 + SSD1306 + push button,
//!   runnable in the browser at wokwi.com (Bluetooth and I²S are not
//!   simulated there, so they are compiled out by default).
//! * `zephyr` — a starting skeleton for the production nRF52840 board:
//!   devicetree overlay, `prj.conf`, threads for sensors / audio / UI / power.
//!
//! APIs used are the ones documented by each project (Adafruit Bluefruit
//! nRF52 library, Arduino-ESP32 BLE, U8g2, Zephyr's GATT/sensor/DMIC/SPI
//! drivers); anything board-specific is marked "check".

