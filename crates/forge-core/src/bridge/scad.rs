//! OpenSCAD export: a readable, *parametric* program that regenerates the
//! Iris frame approximately from `design.frame` (and the optics housing from
//! `design.optics`), so it can be edited in the OpenSCAD Playground
//! (<https://ochafik.com/openscad2>) or desktop OpenSCAD and re-exported as STL.
//!
//! It is deliberately a *simplified* re-statement of the Rust generator in
//! `cad::frame` (superellipse lens openings, offset rims, a bridge bar,
//! drafted extrusions, pods with a hollow cavity and temples with the ear
//! bend) — the numbers are the project's, the shapes are close but not
//! identical. Draft is applied with `linear_extrude(scale = …)`: a wall of
//! height h shrinks the outline by h·tan(draft) on each side, so the scale
//! about the outline's centre is (w − 2h·tan θ)/w.
//!
//! Reference: OpenSCAD User Manual, <https://openscad.org/documentation.html>
//! (2D subsystem, `linear_extrude`, `offset`, the Customizer comments).

use crate::project::Project;

fn n(v: f64) -> String {
    super::util::num(v)
}

/// The OpenSCAD source for the project's frame.
pub fn openscad(p: &Project) -> String {
    let f = &p.design.frame;
    let o = &p.design.optics;
    let mut s = String::new();
    s += &format!(
        "// {} v{} — parametric frame (approximate), generated by Protoforge\n",
        p.meta.name, p.meta.version
    );
    s += "// Open in the OpenSCAD Playground (https://ochafik.com/openscad2) or desktop OpenSCAD.\n";
    s += "// Edit the parameters (or use the Customizer panel), F5 = preview, F6 = render, then export STL/3MF.\n";
    s += "// Units: millimetres. Axes: X = wearer's right, Y = forward (temples run towards -Y), Z = up.\n";
    s += "// This is a simplified re-statement of Protoforge's CAD generator: same parameters, close shapes.\n\n";
    s += "/* [Boxing system (ISO 8624): A - DBL - temple] */\n";
    s += &format!("lens_width = {}; // A: horizontal width of one lens box\n", n(f.lens_width_mm));
    s += &format!("lens_height = {}; // B: vertical height of one lens box\n", n(f.lens_height_mm));
    s += &format!("bridge = {}; // DBL: distance between lenses\n", n(f.bridge_mm));
    s += &format!("temple_length = {}; // hinge to temple tip\n\n", n(f.temple_length_mm));
    s += "/* [Front] */\n";
    s += &format!("front_thickness = {};\n", n(f.front_thickness_mm));
    s += &format!("rim_width = {};\n", n(f.rim_width_mm));
    s += &format!("lens_shape_exponent = {}; // 2 = ellipse, 4+ = squarer\n", n(f.lens_shape_exponent));
    s += &format!(
        "pantoscopic_tilt = {}; // degrees, front tilted towards the cheeks\n\n",
        n(f.pantoscopic_tilt_deg)
    );
    s += "/* [Temples and pods] */\n";
    s += &format!("temple_width = {};\n", n(f.temple_width_mm));
    s += &format!("temple_height = {};\n", n(f.temple_height_mm));
    s += &format!("pod_length = {}; // right pod: electronics\n", n(f.pod_length_mm));
    s += &format!("pod_width = {};\n", n(f.pod_width_mm));
    s += &format!("pod_height = {};\n", n(f.pod_height_mm));
    s += &format!("battery_pod_length = {}; // left pod: battery\n", n(f.battery_pod_length_mm));
    s += &format!("wall = {};\n\n", n(f.wall_mm));
    s += "/* [Optics housing (right eye)] */\n";
    s += "show_optics_housing = true;\n";
    s += &format!("lens_diameter = {};\n", n(o.lens_diameter_mm));
    s += &format!("display_to_lens = {};\n", n(o.display_to_lens_mm));
    s += &format!("lens_to_combiner = {};\n\n", n(o.lens_to_combiner_mm));
    s += "/* [Molding] */\n";
    s += &format!("draft_deg = {}; // side-wall draft for injection molding\n\n", n(f.draft_deg));
    s += "/* [Quality] */\nsegments = 96;\n\n";
    s += SCAD_BODY;
    s
}

const SCAD_BODY: &str = r##"// ---------------------------------------------------------------- derived
c = (lens_width + bridge) / 2;          // lens centre offset = frame PD / 2
hinge_z = 0.3 * lens_height / 2;        // hinges sit a little above the lens centre
front_half_width = c + lens_width / 2 + rim_width;
ear_length = min(max(0.25 * temple_length, 25), 45);
ear_bend = 38;                          // degrees
eps = 0.01;

// Superellipse |x/a|^n + |y/b|^n = 1 as a polygon (Lamé curve).
function superellipse(a, b, n, k = segments) =
  [for (i = [0 : k - 1])
     let (t = 360 * i / k, ct = cos(t), st = sin(t))
       [a * sign(ct) * pow(abs(ct), 2 / n), b * sign(st) * pow(abs(st), 2 / n)]];

module lens_shape(grow = 0)
  polygon(superellipse(lens_width / 2 + grow, lens_height / 2 + grow, lens_shape_exponent));

// linear_extrude whose side walls taper by draft_deg: an outline of half-width
// w shrinks (or, for holes, grows) by h*tan(draft) per side over height h.
module drafted(h, half_width, grow = false) {
  k = (half_width + (grow ? 1 : -1) * h * tan(draft_deg)) / half_width;
  linear_extrude(height = h, scale = k) children();
}

// ---------------------------------------------------------------- front
module front_outline() {
  bar_h = max(3.5, 0.9 * rim_width);
  union() {
    for (s = [-1, 1]) translate([s * c, 0]) offset(r = rim_width) lens_shape();
    // bridge bar across the top of the nose
    translate([0, 0.62 * (lens_height / 2 + rim_width) - bar_h / 2])
      square([bridge + 2 * rim_width, bar_h], center = true);
    // endpieces: bulges at hinge height that carry the hinge knuckles
    for (s = [-1, 1]) translate([s * (front_half_width - 1), hinge_z])
      scale([1, 1.4]) circle(d = temple_height, $fn = 32);
  }
}

module front() {
  rotate([90 + pantoscopic_tilt, 0, 0])   // outline plane -> XZ, extrusion -> -Y
    difference() {
      drafted(front_thickness, front_half_width) front_outline();
      for (s = [-1, 1]) translate([s * c, 0, -eps])
        drafted(front_thickness + 2 * eps, lens_width / 2, grow = true) lens_shape();
    }
}

// ---------------------------------------------------------------- temples
// A pod: rounded box along -Y, hollow with the opening facing outwards (the lid side).
module pod(len, side) {
  r = min(3, (pod_height - temple_height) / 2 + 1);
  difference() {
    rotate([90, 0, 0]) linear_extrude(height = len)
      offset(r = r) offset(delta = -r) square([pod_width, pod_height], center = true);
    // cavity, open on the outer face (x = side * pod_width / 2)
    translate([side * wall / 2, -wall, 0]) rotate([90, 0, 0]) linear_extrude(height = len - 2 * wall)
      square([pod_width - wall + eps, pod_height - 2 * wall], center = true);
  }
}

module arm(len) {
  straight = len - ear_length;
  // straight part
  translate([-temple_width / 2, -straight, -temple_height / 2]) cube([temple_width, straight, temple_height]);
  // ear bend: tilt the tail down around the end of the straight part
  translate([0, -straight, 0]) rotate([ear_bend, 0, 0])
    translate([-temple_width / 2, -ear_length, -temple_height / 2 * 0.8])
      cube([temple_width, ear_length, temple_height * 0.8]);
}

module temple(side, pod_len) {
  x = side * (front_half_width - pod_width / 2);
  translate([x, -front_thickness, hinge_z]) {
    pod(pod_len, side);
    translate([0, -pod_len + eps, 0]) arm(temple_length - pod_len);
  }
}

// ---------------------------------------------------------------- optics housing
module optics_housing() {
  L = display_to_lens + lens_to_combiner;
  w = lens_diameter + 2 * wall;
  h = 0.6 * lens_diameter + 2 * wall;
  translate([c - w / 2, -front_thickness - L - wall, lens_height / 2 + rim_width - h / 2])
    difference() {
      cube([w, L + wall, h]);
      translate([wall, wall, -eps]) cube([w - 2 * wall, L - wall, h - wall]); // open underneath, towards the combiner
    }
}

// ---------------------------------------------------------------- assembly
color("#3a3f4b") front();
color("#3a3f4b") temple(1, pod_length);          // right: electronics pod
color("#3a3f4b") temple(-1, battery_pod_length); // left: battery pod
if (show_optics_housing) color("#6b7280") optics_housing();
"##;

/// Structural sanity check used by the tests (and the web page): balanced
/// brackets outside strings/comments, every statement terminated, every
/// parameter the program uses defined.
pub fn check(src: &str) -> Result<(), String> {
    let mut depth = [0i32; 3];
    let (mut in_str, mut line_c, mut block_c) = (false, false, false);
    let b: Vec<char> = src.chars().collect();
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        let nx = b.get(i + 1).copied().unwrap_or('\0');
        if line_c {
            if c == '\n' {
                line_c = false;
            }
        } else if block_c {
            if c == '*' && nx == '/' {
                block_c = false;
                i += 1;
            }
        } else if in_str {
            if c == '\\' {
                i += 1;
            } else if c == '"' {
                in_str = false;
            }
        } else {
            match c {
                '/' if nx == '/' => line_c = true,
                '/' if nx == '*' => block_c = true,
                '"' => in_str = true,
                '(' => depth[0] += 1,
                ')' => depth[0] -= 1,
                '[' => depth[1] += 1,
                ']' => depth[1] -= 1,
                '{' => depth[2] += 1,
                '}' => depth[2] -= 1,
                _ => {}
            }
            if depth.iter().any(|d| *d < 0) {
                return Err(format!("unbalanced bracket at char {i}"));
            }
        }
        i += 1;
    }
    if depth != [0, 0, 0] || in_str || block_c {
        return Err(format!("unbalanced at end: {depth:?}"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn iris_scad_is_balanced_and_parametric() {
        let p = Project::iris();
        let s = openscad(&p);
        check(&s).unwrap();
        assert!(s.contains("lens_width = 50;"));
        assert!(s.contains("bridge = 18;"));
        assert!(s.contains("draft_deg = 1.5;"));
        assert!(s.contains("linear_extrude(height = h, scale = k)"));
        // every parameter used by the body is assigned in the header
        for name in [
            "lens_width",
            "lens_height",
            "bridge",
            "temple_length",
            "front_thickness",
            "rim_width",
            "lens_shape_exponent",
            "pantoscopic_tilt",
            "temple_width",
            "temple_height",
            "pod_length",
            "pod_width",
            "pod_height",
            "battery_pod_length",
            "wall",
            "lens_diameter",
            "display_to_lens",
            "lens_to_combiner",
            "draft_deg",
            "segments",
        ] {
            assert!(s.contains(&format!("\n{name} = ")), "{name} not defined");
        }
        // parameters follow the project
        let mut q = p.clone();
        q.design.frame.bridge_mm = 21.5;
        assert!(openscad(&q).contains("bridge = 21.5;"));
    }

    #[test]
    fn checker_catches_errors() {
        assert!(check("a = [1, 2;").is_err());
        assert!(check("module m() { cube(1); } // )").is_ok());
        assert!(check("x = \"(\";").is_ok());
    }
}
