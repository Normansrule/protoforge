//! # Bridge — Protoforge's web toolchain and version history engine
//!
//! Protoforge simulates everything in the browser; this module hands the
//! results to the real engineering tools people use next, and compares
//! versions of a design:
//!
//! | file | what |
//! |---|---|
//! | [`kicad`] | `.kicad_pcb` (KiCad 7/8 board with footprints, tracks, vias, zones, keep-outs), `.kicad_pro` with net classes, S-expression netlist, `.pretty` footprint library |
//! | [`step`] | ISO 10303-21 STEP (AP214) faceted B-rep of every frame part, in mm, with colours |
//! | [`scad`] | a parametric OpenSCAD program that regenerates the frame |
//! | [`falstad`] + [`lzstring`] | Circuit Lab presets → Falstad CircuitJS text and `?ctz=` links |
//! | [`rayoptics`] | the heads-up display as a Ray Optics Simulation scene |
//! | [`diff`] | Onshape-style version comparison with requirement verdict changes |
//!
//! Every exporter is re-parsed in its unit tests (and, outside the test
//! suite, with independent parsers — see `docs/toolchain.md`).

