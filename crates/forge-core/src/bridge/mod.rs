fn utf8(path: impl Into<String>, content: impl Into<String>) -> PackageFile {
    PackageFile {
        path: path.into(),
        content: content.into(),
        encoding: "utf8".into(),
    }
}

fn b64(path: impl Into<String>, bytes: &[u8]) -> PackageFile {
    PackageFile {
        path: path.into(),
        content: util::base64(bytes),
        encoding: "base64".into(),
    }
}

/// Options for [`export_all`].
#[derive(Clone, Debug, Deserialize)]
#[serde(default)]
pub struct ExportOptions {
    /// Include G-code for every frame part (slower).
    pub gcode: bool,
    /// ISO 8601 time stamp written into the STEP header.
    pub timestamp: String,
}

impl Default for ExportOptions {
    fn default() -> Self {
        ExportOptions {
            gcode: true,
            timestamp: String::new(),
        }
    }
}

