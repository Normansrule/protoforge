#[derive(Deserialize)]
struct ProjectIn {
    project: Project,
}

#[derive(Deserialize)]
struct StepIn {
    project: Project,
    #[serde(default)]
    frame: step::StepFrame,
    #[serde(default)]
    timestamp: String,
}

#[derive(Deserialize)]
struct TextIn {
    text: String,
}

#[derive(Deserialize)]
struct DiffIn {
    a: Project,
    b: Project,
}

#[derive(Deserialize)]
struct SummaryIn {
    project: Project,
    #[serde(default)]
    evaluate: bool,
}

#[derive(Deserialize)]
struct FalstadIn {
    project: Project,
    #[serde(default)]
    id: Option<String>,
}

#[derive(Deserialize)]
struct ExportIn {
    project: Project,
    #[serde(default)]
    options: ExportOptions,
}

#[derive(Deserialize)]
struct NetlistIn {
    netlist: String,
    #[serde(default)]
    title: String,
}

/// JSON API entry point for `bridge.*` methods.
pub fn dispatch(method: &str, input: &Value) -> Option<ApiResult> {
    match method {
        "bridge.kicad_pcb" => handle(input, |i: ProjectIn| Ok(kicad::kicad_pcb(&i.project))),
        "bridge.kicad_project" => handle(input, |i: ProjectIn| Ok(kicad::kicad_pro(&i.project))),
        "bridge.kicad_netlist" => handle(input, |i: ProjectIn| Ok(kicad::kicad_netlist(&i.project))),
        "bridge.kicad_footprints" => handle(input, |i: ProjectIn| Ok(kicad::footprint_library(&i.project))),
        "bridge.step" => handle(input, |i: StepIn| Ok(step::step(&i.project, i.frame, &i.timestamp))),
        "bridge.openscad" => handle(input, |i: ProjectIn| Ok(scad::openscad(&i.project))),
        "bridge.ray_optics" => handle(input, |i: ProjectIn| Ok(rayoptics::scene(&i.project))),
        "bridge.falstad" => handle(input, |i: FalstadIn| {
            let all = falstad::all(&i.project);
            Ok(match i.id {
                Some(id) => all.into_iter().filter(|c| c.id == id).collect::<Vec<_>>(),
                None => all,
            })
        }),
        "bridge.falstad_netlist" => handle(input, |i: NetlistIn| {
            let t = if i.title.is_empty() { "netlist".to_string() } else { i.title.clone() };
            Ok(falstad::convert("custom", &t, "Custom", &i.netlist, None))
        }),
        "bridge.lz_compress" => handle(input, |i: TextIn| Ok(lzstring::compress_to_encoded_uri_component(&i.text))),
        "bridge.lz_decompress" => handle(input, |i: TextIn| {
            lzstring::decompress_from_encoded_uri_component(&i.text).ok_or_else(|| "not a valid lz-string URI component".to_string())
        }),
        "bridge.export_all" => handle(input, |i: ExportIn| Ok(export_all(&i.project, &i.options))),
        "bridge.diff" => handle(input, |i: DiffIn| Ok(diff::diff(&i.a, &i.b))),
        "bridge.summary" => handle(input, |i: SummaryIn| {
            let ev = i.evaluate.then(|| crate::systems::evaluate(&i.project));
            Ok(diff::summary(&i.project, ev.as_ref()))
        }),
        "bridge.example_history" => Some(crate::api::to_value(diff::iris_history())),
        _ => None,
    }
}

/// The bridge only translates; it contributes no requirement metrics.
pub fn metrics(_p: &Project) -> Vec<Metric> {
    vec![]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn export_all_contains_every_tool_folder() {
        let p = Project::iris();
        let files = export_all(
            &p,
            &ExportOptions {
                gcode: false,
                timestamp: "2026-09-28T00:00:00".into(),
            },
        );
        let has = |pre: &str| files.iter().any(|f| f.path.starts_with(pre));
        for pre in ["README.md", "kicad/iris.kicad_pcb", "kicad/iris.kicad_pro", "kicad/Protoforge.pretty/", "pcb/", "cad/iris-frame.step", "cad/iris-frame.scad", "cad/stl/", "circuits/", "chip/", "optics/", "project.json"] {
            assert!(has(pre), "missing {pre}");
        }
        let mut paths: Vec<&str> = files.iter().map(|f| f.path.as_str()).collect();
        paths.sort();
        let n = paths.len();
        paths.dedup();
        assert_eq!(n, paths.len(), "duplicate paths");
    }

    #[test]
    fn api_methods_answer() {
        let p = serde_json::to_value(Project::iris()).unwrap();
        let v = crate::api::call_value("bridge.lz_compress", &serde_json::json!({ "text": "hello world" })).unwrap();
        assert_eq!(v, "BYUwNmD2AEDukCcwBMg");
        let s = crate::api::call_value("bridge.summary", &serde_json::json!({ "project": p })).unwrap();
        assert_eq!(s["hash"].as_str().unwrap().len(), 16);
        let h = crate::api::call_value("bridge.example_history", &Value::Null).unwrap();
        assert_eq!(h.as_array().unwrap().len(), 2);
    }
}
