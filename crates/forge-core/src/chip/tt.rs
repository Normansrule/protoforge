//! Tiny Tapeout packaging of the IRIS-DSP co-processor.
//!
//! `tt_um_iris_dsp` uses the standard Tiny Tapeout user-module ports
//! (`ui_in[7:0]`, `uo_out[7:0]`, `uio_in[7:0]`, `uio_out[7:0]`,
//! `uio_oe[7:0]`, `ena`, `clk`, `rst_n`) and instantiates the CIC
//! decimator, the decimation FIR and the gesture FSM. See
//! <https://tinytapeout.com> and <https://github.com/TinyTapeout/tt-support-tools>.

use serde::Serialize;

use super::firgen::{self, CicSpec, FirGen};
use super::fsm::{self, Encoding, Fsm};

#[derive(Clone, Debug, Serialize)]
pub struct File {
    pub name: String,
    pub content: String,
}

fn clog2(x: u64) -> u32 {
    if x <= 1 {
        0
    } else {
        64 - (x - 1).leading_zeros()
    }
}

pub fn top_verilog(cic: &CicSpec, fir: &FirGen, clock_mhz: f64) -> String {
    let w = cic.width;
    let d = fir.data_bits;
    let div = (clock_mhz * 1000.0).round().max(2.0) as u64; // clk / 1 kHz
    let dw = clog2(div).max(1);
    format!(
        r#"// Generated by Protoforge Chip Lab — IRIS-DSP co-processor for Tiny Tapeout
// PDM microphone → CIC (N={n}, R={r}) → {taps}-tap FIR (↓{decim}) → 16 kHz PCM, plus the touch-gesture FSM.
//
// Pin map
//   ui_in[0]   PDM data from the microphone
//   ui_in[1]   PDM clock (driven by the host alongside the mic, ~1.024 MHz)
//   ui_in[2]   touch (from the capacitive touch controller, active high)
//   ui_in[3]   byte select for uo_out: 0 = PCM[7:0], 1 = PCM[15:8]
//   uo_out     PCM sample byte (latest sample, two's complement)
//   uio_out[0] sample strobe (toggles on every new PCM sample)
//   uio_out[1] tap pulse, [2] double-tap pulse, [3] long-press pulse (one 1 ms tick each)
//   uio_out[6:4] gesture FSM state, [7] 0
`timescale 1ns/1ps
`default_nettype none

module tt_um_iris_dsp (
    input  wire [7:0] ui_in,
    output wire [7:0] uo_out,
    input  wire [7:0] uio_in,
    output wire [7:0] uio_out,
    output wire [7:0] uio_oe,
    input  wire       ena,
    input  wire       clk,
    input  wire       rst_n
);
    // ---- two-flop synchronisers for the asynchronous inputs
    reg [2:0] pclk_s;
    reg [1:0] pdat_s;
    reg [1:0] touch_s;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pclk_s <= 3'b000; pdat_s <= 2'b00; touch_s <= 2'b00;
        end else begin
            pclk_s  <= {{pclk_s[1:0], ui_in[1]}};
            pdat_s  <= {{pdat_s[0], ui_in[0]}};
            touch_s <= {{touch_s[0], ui_in[2]}};
        end
    end
    wire pdm_strobe = pclk_s[1] & ~pclk_s[2];   // rising edge of the PDM clock
    wire pdm_bit    = pdat_s[1];

    // ---- CIC decimator (PDM rate → PDM rate / {r})
    wire              cic_v;
    wire signed [{wm}:0] cic_y;
    iris_cic u_cic (.clk(clk), .rst_n(rst_n), .in_valid(pdm_strobe), .pdm(pdm_bit), .out_valid(cic_v), .y(cic_y));
    // keep the top {d} bits (CIC gain (RM)^N = 2^{gain_bits}; 6 dB headroom)
    wire signed [{dm}:0] fir_x = cic_y[{wm}:{shift}];

    // ---- decimation FIR ({arch:?})
    wire              fir_v;
    wire signed [{dm}:0] fir_y;
    iris_fir u_fir (.clk(clk), .rst_n(rst_n), .in_valid(cic_v), .x_in(fir_x), .out_valid(fir_v), .y_out(fir_y));

    reg [{dm}:0] sample;
    reg        strobe;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            sample <= {d}'d0; strobe <= 1'b0;
        end else if (fir_v) begin
            sample <= fir_y; strobe <= ~strobe;
        end
    end

    // ---- 1 kHz tick for the gesture FSM (clk = {clock_mhz} MHz)
    reg [{dwm}:0] div;
    reg        tick;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            div <= {dw}'d0; tick <= 1'b0;
        end else begin
            tick <= (div == {dw}'d{divm});
            div  <= (div == {dw}'d{divm}) ? {dw}'d0 : div + {dw}'d1;
        end
    end

    wire       tap, dtap, lpress;
    wire [2:0] fsm_state;
    iris_gesture_fsm u_fsm (.clk(clk), .rst_n(rst_n), .tick(tick), .touch(touch_s[1]),
                            .tap(tap), .double_tap(dtap), .long_press(lpress), .state_idx(fsm_state));

    assign uo_out  = ui_in[3] ? sample[{dm}:{half}] : sample[{halfm}:0];
    assign uio_out = {{1'b0, fsm_state, lpress, dtap, tap, strobe}};
    assign uio_oe  = 8'hFF;

    // unused inputs (keeps lint quiet)
    wire _unused = &{{ena, ui_in[7:4], uio_in, cic_y[{shiftm}:0], 1'b0}};
endmodule

`default_nettype wire
"#,
        n = cic.order,
        r = cic.rate,
        taps = fir.taps,
        decim = fir.decim,
        wm = w - 1,
        dm = d - 1,
        shift = w - d,
        gain_bits = (cic.order as f64 * ((cic.rate * cic.diff_delay) as f64).log2()).round(),
        arch = fir.arch,
        dwm = dw - 1,
        divm = div - 1,
        half = d / 2,
        halfm = d / 2 - 1,
        shiftm = w - d - 1,
    )
}

/// End-to-end testbench: drives a PDM stream (from the Rust sigma-delta
/// modulator) into `tt_um_iris_dsp` and compares every PCM sample with the
/// bit-exact Rust model (CIC → bit slice → FIR reference convolution).
pub fn top_testbench(cic: &CicSpec, fir: &FirGen, codes: &[i64], bits: &[bool]) -> String {
    let d = fir.data_bits;
    let cic_y = firgen::model_cic(bits, cic);
    let shift = cic.width - d;
    let x: Vec<i64> = cic_y.iter().map(|v| v >> shift).collect();
    let y = firgen::reference_output(codes, &x, fir.frac_bits, d, fir.decim);
    let mask = (1u64 << d) - 1;
    let (bw, bh) = fsm::pack_hex(&bits.iter().map(|&b| b as u32).collect::<Vec<_>>(), 1);
    let (yw, yh) = fsm::pack_hex(&y.iter().map(|&v| (v as u64 & mask) as u32).collect::<Vec<_>>(), d);
    format!(
        r#"// End-to-end testbench generated by Protoforge Chip Lab: PDM bits in, PCM out,
// compared with the bit-exact Rust model of the CIC + FIR.
// Run:  iverilog -g2005 -o tb_top tt_um_iris_dsp.v iris_cic.v iris_fir.v iris_gesture_fsm.v tb_tt_um_iris_dsp.v && vvp tb_top
`timescale 1ns/1ps

module tb_tt_um_iris_dsp;
    reg clk = 1'b0, rst_n = 1'b0;
    reg [7:0] ui_in = 8'h00;
    reg [7:0] uio_in = 8'h00;
    wire [7:0] uo_out, uio_out, uio_oe;
    tt_um_iris_dsp dut (.ui_in(ui_in), .uo_out(uo_out), .uio_in(uio_in), .uio_out(uio_out), .uio_oe(uio_oe),
                        .ena(1'b1), .clk(clk), .rst_n(rst_n));
    always #10 clk = ~clk;   // 50 MHz

    localparam integer NB = {nb};
    localparam integer NY = {ny};
    localparam [{bwm}:0] BITS = {bw}'h{bh};
    localparam [{ywm}:0] YS   = {yw}'h{yh};

    integer i, k = 0, errors = 0;
    reg last_strobe = 1'b0;
    reg [{dm}:0] got;

    // read both bytes whenever the sample strobe toggles
    always @(negedge clk) begin
        if (rst_n && uio_out[0] != last_strobe) begin
            last_strobe = uio_out[0];
            ui_in[3] = 1'b0; #1 got[{halfm}:0] = uo_out;
            ui_in[3] = 1'b1; #1 got[{dm}:{half}] = uo_out;
            ui_in[3] = 1'b0;
            if (k < NY && got !== YS[{d}*k +: {d}]) begin
                errors = errors + 1;
                if (errors < 10) $display("sample %0d: got %0d, expected %0d", k, $signed(got), $signed(YS[{d}*k +: {d}]));
            end
            k = k + 1;
        end
    end

    initial begin
        $dumpfile("tb_tt_um_iris_dsp.vcd");
        $dumpvars(0, tb_tt_um_iris_dsp);
        repeat (4) @(posedge clk);
        #1 rst_n = 1'b1;
        for (i = 0; i < NB; i = i + 1) begin
            ui_in[0] = BITS[i];            // data changes while the PDM clock is low
            repeat (24) @(posedge clk);
            ui_in[1] = 1'b1;               // rising edge: the chip samples the bit
            repeat (24) @(posedge clk);
            ui_in[1] = 1'b0;
        end
        repeat (200) @(posedge clk);
        if (k < NY) begin
            $display("FAIL: %0d samples, expected %0d", k, NY);
            errors = errors + 1;
        end
        if (errors == 0) $display("PASS: %0d PCM samples match the Rust model", NY);
        else $display("FAIL: %0d errors", errors);
        $finish;
    end
endmodule
"#,
        nb = bits.len(),
        ny = y.len(),
        bwm = bw - 1,
        ywm = yw - 1,
        dm = d - 1,
        half = d / 2,
        halfm = d / 2 - 1,
    )
}

pub fn readme(cic: &CicSpec, fir: &FirGen, f: &Fsm, enc: Encoding, clock_mhz: f64, total_cells: f64, crit_ns: f64) -> String {
    format!(
        r#"# IRIS-DSP — Tiny Tapeout package

Generated by the Protoforge **Chip Lab** for the Iris smart glasses.

`tt_um_iris_dsp` turns a PDM MEMS microphone stream into 16 kHz PCM and
recognises touch gestures on the temple:

| Block | What |
|---|---|
| `iris_cic.v` | CIC decimator, N = {n}, R = {r}, M = 1, {w}-bit registers |
| `iris_fir.v` | {taps}-tap droop-compensating FIR, Q0.{frac} coefficients ({arch:?} architecture), ↓{decim} |
| `iris_gesture_fsm.v` | Moore FSM ({states} states, {enc:?} encoding): tap / double tap / long press |
| `tt_um_iris_dsp.v` | Tiny Tapeout top level: synchronisers, 1 kHz tick, output mux |

Estimated size ≈ {cells:.0} standard cells; estimated critical path {crit:.1} ns
(clock {clock_mhz} MHz). These are Protoforge's first-order estimates — the
synthesis and place-and-route reports are the real numbers.

## Pins

| Pin | Direction | Function |
|---|---|---|
| `ui_in[0]` | in | PDM data |
| `ui_in[1]` | in | PDM clock (host drives the mic clock, ~1.024 MHz, and mirrors it here) |
| `ui_in[2]` | in | touch (active high) |
| `ui_in[3]` | in | `uo_out` byte select (0 = low byte, 1 = high byte) |
| `uo_out[7:0]` | out | latest PCM sample byte |
| `uio_out[0]` | out | sample strobe (toggles per sample) |
| `uio_out[1]` / `[2]` / `[3]` | out | tap / double tap / long press (1 ms pulses) |
| `uio_out[6:4]` | out | gesture FSM state |

## Simulate

```sh
iverilog -g2005 -o tb_fir iris_fir.v tb_iris_fir.v && vvp tb_fir
iverilog -g2005 -o tb_fsm iris_gesture_fsm.v tb_iris_gesture_fsm.v && vvp tb_fsm
iverilog -g2005 -o tb_top tt_um_iris_dsp.v iris_cic.v iris_fir.v iris_gesture_fsm.v tb_tt_um_iris_dsp.v && vvp tb_top
gtkwave tb_tt_um_iris_dsp.vcd   # optional waveform viewer
```

## Synthesise (quick area check)

```sh
yosys -p "read_verilog tt_um_iris_dsp.v iris_cic.v iris_fir.v iris_gesture_fsm.v; synth -top tt_um_iris_dsp; stat"
```

## Submit to Tiny Tapeout

1. Start from the current Verilog template repository linked from
   <https://tinytapeout.com> (the `tt*-verilog-template` repositories) and copy
   these `.v` files into its `src/` folder.
2. Fill in `info.yaml` following the template's comments: top module
   `tt_um_iris_dsp`, the source file list, the clock frequency and the pin
   descriptions above. (Field names change between shuttles, so follow the
   template rather than this README.)
3. Push to GitHub; the template's Actions run the hardening flow
   (OpenLane / OpenROAD on SkyWater sky130) and render the GDS. To harden
   locally, follow the "local hardening" guide in the Tiny Tapeout docs, which
   uses `tt-support-tools` (<https://github.com/TinyTapeout/tt-support-tools>).
4. Choose the tile count from the utilisation report.

## Test on the board

Drive the PDM clock from the RP2040 on the Tiny Tapeout demo board (or any
MCU) to both the microphone and `ui_in[1]`, wire the mic data to `ui_in[0]`,
and read the PCM bytes on every `uio_out[0]` toggle.
"#,
        n = cic.order,
        r = cic.rate,
        w = cic.width,
        taps = fir.taps,
        frac = fir.frac_bits,
        arch = fir.arch,
        decim = fir.decim,
        states = f.states.len(),
        enc = enc,
        cells = total_cells,
        crit = crit_ns,
    )
}
