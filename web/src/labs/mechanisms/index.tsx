// Mechanisms Lab: four-bar and slider-crank linkages, helical springs,
// involute gears, cams, and the Iris spring hinge — analysed in the Rust
// engine (crates/forge-core/src/mechanisms) and animated here.
import { Link, useSearchParams } from 'react-router-dom';
import { LabPage } from '../../components/LabPage';
import { Tabs } from '../../components/ui';
import { LinkagesTab } from './LinkagesTab';
import { SpringsTab } from './SpringsTab';
import { GearsTab } from './GearsTab';
import { CamsTab } from './CamsTab';
import { HingeTab } from './HingeTab';
import { LearnTab } from './LearnTab';
import './mechanisms.css';

type Tab = 'linkages' | 'springs' | 'gears' | 'cams' | 'hinge' | 'learn';
const TABS: { id: Tab; label: string }[] = [
  { id: 'linkages', label: 'Linkages' },
  { id: 'springs', label: 'Springs' },
  { id: 'gears', label: 'Gears' },
  { id: 'cams', label: 'Cams' },
  { id: 'hinge', label: 'Iris hinge' },
  { id: 'learn', label: 'How it works' },
];

export default function Lab() {
  const [params, setParams] = useSearchParams();
  const q = params.get('tab') as Tab | null;
  const tab: Tab = q && TABS.some((t) => t.id === q) ? q : 'linkages';
  const setTab = (t: Tab) => setParams((p) => { const n = new URLSearchParams(p); n.set('tab', t); return n; }, { replace: true });
  return (
    <LabPage
      kicker="Optics & Mechanics · Lab"
      title="Mechanisms Lab"
      subtitle={
        <>
          Design things that move. Four-bar and slider-crank linkages solved by vector loops (Freudenstein's equation) with draggable pivots and coupler curves; helical
          compression, extension and torsion springs per Shigley with Goodman–Zimmerli fatigue; true involute spur gears generated by a rounded ISO 53 rack, meshing along the
          line of action, with Lewis bending and DXF/SVG export; cam displacement, velocity, acceleration and jerk (SVAJ) with roller-follower profiles — and the{' '}
          <b>Iris spring hinge</b>: torque vs opening angle, clamp on the head, spring stress and life. Snap fits and screws live in the{' '}
          <Link to="/structures">Structures Lab</Link>.
        </>
      }
      metricPrefixes={['mechanisms.']}
    >
      <Tabs tabs={TABS} value={tab} onChange={setTab} />
      {tab === 'linkages' && <LinkagesTab />}
      {tab === 'springs' && <SpringsTab />}
      {tab === 'gears' && <GearsTab />}
      {tab === 'cams' && <CamsTab />}
      {tab === 'hinge' && <HingeTab />}
      {tab === 'learn' && <LearnTab />}
    </LabPage>
  );
}
