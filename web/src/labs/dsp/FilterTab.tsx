type Band = 'lowpass' | 'highpass' | 'bandpass' | 'bandstop';
type BiquadKind = 'lowpass' | 'highpass' | 'bandpass' | 'notch' | 'peaking' | 'low_shelf' | 'high_shelf' | 'allpass';

interface FState {
  kind: 'fir' | 'iir';
  band: Band;
  method: 'window' | 'kaiser' | 'ls';
  window: WindowKind;
  beta: number;
  taps: number;
  f1: number;
  f2: number;
  atten: number;
  trans: number;
  family: 'butterworth' | 'rbj';
  biquad: BiquadKind;
  order: number;
  highpass: boolean;
  f0: number;
  q: number;
  gain: number;
}

const INIT: FState = {
  kind: 'fir', band: 'lowpass', method: 'window', window: 'hamming', beta: 8.6, taps: 63, f1: 3400, f2: 5000, atten: 60, trans: 800,
  family: 'butterworth', biquad: 'peaking', order: 4, highpass: false, f0: 1000, q: 0.707, gain: 6,
};

export function cHeader(name: string, b: number[], a: number[] | null, bits: number): string {
  const q = (v: number[]) => {
    const maxAbs = Math.max(...v.map(Math.abs), 1e-12);
    let intBits = 0;
    while (2 ** intBits <= maxAbs && intBits < bits - 1) intBits++;
    const frac = bits - 1 - intBits;
    return { frac, codes: v.map((x) => Math.max(-(2 ** (bits - 1)), Math.min(2 ** (bits - 1) - 1, Math.round(x * 2 ** frac)))) };
  };
  const qb = q(b);
  const lines = [
    `// ${name} — generated by the Protoforge DSP Lab`,
    `// y[n] = Σ b[k]·x[n−k]${a ? ' − Σ a[k]·y[n−k] (a[0] = 1)' : ''}`,
    '#pragma once',
    '#include <stdint.h>',
    '',
    `#define ${name.toUpperCase()}_NB ${b.length}`,
    `static const float ${name}_b[${b.length}] = {\n    ${b.map((v) => v.toExponential(9) + 'f').join(',\n    ')}\n};`,
  ];
  if (a) lines.push(`#define ${name.toUpperCase()}_NA ${a.length}`, `static const float ${name}_a[${a.length}] = {\n    ${a.map((v) => v.toExponential(9) + 'f').join(',\n    ')}\n};`);
  lines.push('', `// Q${bits - 1 - qb.frac}.${qb.frac} fixed point (${bits}-bit): value = code / 2^${qb.frac}`, `#define ${name.toUpperCase()}_B_FRAC_BITS ${qb.frac}`);
  lines.push(`static const int${bits <= 16 ? 16 : 32}_t ${name}_b_q[${b.length}] = { ${qb.codes.join(', ')} };`);
  return lines.join('\n') + '\n';
}

export function FilterTab(props: { spec: SignalSpec }) {
  const [s, setS] = useState<FState>(INIT);
  const set = (p: Partial<FState>) => setS((o) => ({ ...o, ...p }));
  const [view, setView] = useState<'mag' | 'phase' | 'gd'>('mag');
  const [logF, setLogF] = useState(false);
  const [coeffBits, setCoeffBits] = useState(12);
  const [dataBits, setDataBits] = useState(16);
  const fs = props.spec.fs;
  const nyq = fs / 2;
  const f1 = Math.min(s.f1, nyq * 0.98);
  const f2 = Math.min(Math.max(s.f2, f1 + 10), nyq * 0.99);
  const input =
    s.kind === 'fir'
      ? { band: s.band, method: s.method, window: s.window, beta: s.beta, taps: s.taps, f1, f2, fs, atten_db: s.atten, transition_hz: s.trans, n_points: 512, log: logF }
      : { family: s.family, biquad: s.biquad, order: s.order, highpass: s.highpass, f0: Math.min(s.f0, nyq * 0.98), q: s.q, gain_db: s.gain, fs, n_points: 512, log: logF };
  const r = useCompute<FilterReport>(s.kind === 'fir' ? 'dsp.fir_design' : 'dsp.iir_design', input);
  const d = r.data;
  const sig = useCompute<AnalyzeOut>('dsp.analyze', { spec: props.spec, window: 'blackman', beta: 0 });
  const applied = useMemo(() => {
    if (!d || !sig.data) return null;
    const y = tryCall<{ y: number[] }>('dsp.apply', d.sections.length ? { sos: d.sections, x: sig.data.signal.x } : { b: d.b, a: d.a, x: sig.data.signal.x }).data?.y;
    if (!y) return null;
    const sp = tryCall<{ freq: number[]; db: number[] }>('dsp.spectrum', { x: y, fs, window: 'blackman' }).data;
    return { y, sp };
  }, [d, sig.data, fs]);
  const fixed = useCompute<FixedOut>(
    'dsp.fixed_point',
    d && sig.data ? { ...(d.sections.length ? { sos: d.sections } : { b: d.b, a: d.a }), fs, coeff_bits: coeffBits, data_bits: dataBits, x: sig.data.signal.x.slice(0, 2048), n_points: 400 } : null,
    !!d && !!sig.data,
  );
  const cut = s.kind === 'fir' ? (s.band === 'bandpass' || s.band === 'bandstop' ? [f1, f2] : [f1]) : [Math.min(s.f0, nyq * 0.98)];
  const name = s.kind === 'fir' ? `fir_${s.band}` : s.family === 'rbj' ? `biquad_${s.biquad}` : `butter${s.order}_${s.highpass ? 'hp' : 'lp'}`;
  const tfJson = () => JSON.stringify({ name, fs, b: d?.b, a: d?.a, sections: d?.sections, notes: d?.notes }, null, 2);
  const playFiltered = (which: 'dry' | 'wet') => {
    const x = tryCall<{ x: number[] }>('dsp.signal', { ...props.spec, n: Math.round(fs * 1.5) }).data?.x;
    if (!x || !d) return null;
    if (which === 'dry') return { x, fs };
    const y = tryCall<{ y: number[] }>('dsp.apply', d.sections.length ? { sos: d.sections, x } : { b: d.b, a: d.a, x }).data?.y;
    return y ? { x: y, fs } : null;
  };
  return (
    <div className="stack">
      <div className="grid grid-sidebar">
        <Card title="Design" subtitle={`fs = ${fs / 1000} kHz (from the signal builder)`}>
          <Seg value={s.kind} options={[{ value: 'fir', label: 'FIR' }, { value: 'iir', label: 'IIR' }]} onChange={(v) => set({ kind: v })} />
          {s.kind === 'fir' ? (
            <>
              <Select label="Response" value={s.band} options={[{ value: 'lowpass', label: 'Low-pass' }, { value: 'highpass', label: 'High-pass' }, { value: 'bandpass', label: 'Band-pass' }, { value: 'bandstop', label: 'Band-stop' }]} onChange={(v) => set({ band: v as Band })} />
              <Select label="Method" value={s.method} options={[{ value: 'window', label: 'Windowed sinc' }, { value: 'kaiser', label: 'Kaiser (from specs)' }, { value: 'ls', label: 'Least squares' }]} onChange={(v) => set({ method: v as FState['method'] })} />
              <Slider label={s.band === 'bandpass' || s.band === 'bandstop' ? 'Lower edge' : 'Cut-off (−6 dB)'} value={f1} min={20} max={nyq * 0.98} log unit="Hz" onChange={(v) => set({ f1: v })} format={(v) => v.toFixed(0)} />
              {(s.band === 'bandpass' || s.band === 'bandstop') && <Slider label="Upper edge" value={f2} min={20} max={nyq * 0.99} log unit="Hz" onChange={(v) => set({ f2: v })} format={(v) => v.toFixed(0)} />}
              {s.method === 'window' && (
                <>
                  <Slider label="Taps" value={s.taps} min={3} max={255} step={2} onChange={(v) => set({ taps: Math.round(v) | 1 })} format={(v) => v.toFixed(0)} />
                  <Select label="Window" value={s.window} options={(['rectangular', 'hann', 'hamming', 'blackman', 'kaiser'] as WindowKind[]).map((w) => ({ value: w, label: WINDOW_LABEL[w] }))} onChange={(v) => set({ window: v })} />
                  {s.window === 'kaiser' && <Slider label="Kaiser β" value={s.beta} min={0} max={14} step={0.1} onChange={(v) => set({ beta: v })} />}
                </>
              )}
              {s.method === 'kaiser' && (
                <>
                  <Slider label="Stop-band attenuation A" value={s.atten} min={21} max={120} step={1} unit="dB" onChange={(v) => set({ atten: v })} format={(v) => v.toFixed(0)} />
                  <Slider label="Transition width Δf" value={s.trans} min={20} max={nyq / 3} log unit="Hz" onChange={(v) => set({ trans: v })} format={(v) => v.toFixed(0)} />
                </>
              )}
              {s.method === 'ls' && (
                <>
                  <Slider label="Taps" value={s.taps} min={3} max={255} step={2} onChange={(v) => set({ taps: Math.round(v) | 1 })} format={(v) => v.toFixed(0)} />
                  <Slider label="Transition (don't care)" value={s.trans} min={20} max={nyq / 3} log unit="Hz" onChange={(v) => set({ trans: v })} format={(v) => v.toFixed(0)} />
                  <Slider label="Stop-band weight (dB)" value={s.atten} min={0} max={80} step={1} unit="dB" onChange={(v) => set({ atten: v })} format={(v) => v.toFixed(0)} />
                </>
              )}
            </>
          ) : (
            <>
              <Seg value={s.family} options={[{ value: 'butterworth', label: 'Butterworth' }, { value: 'rbj', label: 'RBJ biquad' }]} onChange={(v) => set({ family: v })} />
              {s.family === 'butterworth' ? (
                <>
                  <Slider label="Order N" value={s.order} min={1} max={12} step={1} onChange={(v) => set({ order: Math.round(v) })} format={(v) => v.toFixed(0)} />
                  <Toggle label="High-pass" value={s.highpass} onChange={(v) => set({ highpass: v })} />
                </>
              ) : (
                <Select label="Type" value={s.biquad} options={(['lowpass', 'highpass', 'bandpass', 'notch', 'peaking', 'low_shelf', 'high_shelf', 'allpass'] as BiquadKind[]).map((k) => ({ value: k, label: k.replace('_', ' ') }))} onChange={(v) => set({ biquad: v as BiquadKind })} />
              )}
              <Slider label={s.family === 'butterworth' ? 'Cut-off (−3 dB)' : 'f0'} value={Math.min(s.f0, nyq * 0.98)} min={20} max={nyq * 0.98} log unit="Hz" onChange={(v) => set({ f0: v })} format={(v) => v.toFixed(0)} />
              {s.family === 'rbj' && <Slider label="Q" value={s.q} min={0.1} max={30} log onChange={(v) => set({ q: v })} />}
              {s.family === 'rbj' && (s.biquad === 'peaking' || s.biquad === 'low_shelf' || s.biquad === 'high_shelf') && <Slider label="Gain" value={s.gain} min={-24} max={24} step={0.5} unit="dB" onChange={(v) => set({ gain: v })} />}
            </>
          )}
          {d && (
            <div style={{ marginTop: 6 }}>
              <KV k="Order / taps" v={s.kind === 'fir' ? `${d.taps} taps` : `order ${d.order} (${d.sections.length} biquad${d.sections.length > 1 ? 's' : ''})`} />
              {d.beta != null && <KV k="Kaiser β" v={d.beta.toFixed(3)} />}
              <KV k="Stability" v={<StatusChip status={d.stable ? 'pass' : 'fail'} />} />
              <KV k="Max pole radius" v={d.max_pole_radius.toFixed(4)} />
              {d.notes.map((n) => <p key={n} className="muted small" style={{ margin: '6px 0 0' }}>{n}</p>)}
            </div>
          )}
          <div className="pill-row" style={{ marginTop: 12 }}>
            {d && <DownloadButton small filename={`${name}.csv`} label="CSV" content={() => csvOf(d.a.length > 1 ? { b: d.b, a: d.a } : { h: d.b })} />}
            {d && <DownloadButton small filename={`${name}.h`} label="C header" content={() => cHeader(name, d.b, d.a.length > 1 ? d.a : null, 16)} />}
            {d && <DownloadButton small filename={`${name}.json`} label="JSON" content={tfJson} />}
          </div>
        </Card>
        <div className="stack">
          <Card
            title="Frequency response"
            subtitle={d ? `${r.ms.toFixed(1)} ms in Rust · exact group delay τ = Re{Σ k·c_k e^{−jωk} / Σ c_k e^{−jωk}}` : ''}
            actions={<Toggle label="Log f" value={logF} onChange={setLogF} />}
          >
            <Tabs tabs={[{ id: 'mag', label: 'Magnitude' }, { id: 'phase', label: 'Phase' }, { id: 'gd', label: 'Group delay' }]} value={view} onChange={setView} />
            <ErrorBox error={r.error} />
            {d && view === 'mag' && (
              <Plot height={290} series={[{ name: '|H| (dB)', x: d.freq, y: d.mag_db, width: 2.4 }]} xLabel="frequency (Hz)" yLabel="dB" yDomain={[Math.max(-140, Math.min(-40, ...d.mag_db.filter(isFinite)) - 5), Math.max(3, Math.max(...d.mag_db) + 3)]}
                xLog={logF} xDomain={logF ? [d.freq[0], nyq] : undefined} vLines={cut.map((c) => ({ value: c, color: 'var(--copper)' }))} hLines={[{ value: s.kind === 'fir' ? -6.02 : -3.01, label: s.kind === 'fir' ? '−6 dB' : '−3 dB' }]} />
            )}
            {d && view === 'phase' && <Plot height={290} series={[{ name: 'phase (unwrapped)', x: d.freq, y: d.phase_deg }]} xLabel="frequency (Hz)" yLabel="degrees" xLog={logF} xDomain={logF ? [d.freq[0], nyq] : undefined} />}
            {d && view === 'gd' && <Plot height={290} series={[{ name: 'group delay', x: d.freq, y: d.group_delay }]} xLabel="frequency (Hz)" yLabel="samples" xLog={logF} xDomain={logF ? [d.freq[0], nyq] : undefined} formatY={(v) => fmtNum(v)} />}
          </Card>
          <div className="grid grid-2">
            <Card title="Poles & zeros" subtitle="z-plane; stable ⇔ every pole inside the unit circle">
              {d && <PoleZeroPlot poles={d.poles} zeros={d.zeros} originPoles={d.origin_poles} size={290} />}
            </Card>
            <Card title="Impulse & step response">
              {d && <StemPlot y={d.impulse.slice(0, Math.min(d.impulse.length, s.kind === 'fir' ? d.taps + 4 : 80))} height={150} label="impulse response" xLabel="n (samples)" />}
              {d && <Plot height={130} series={[{ name: 'step', x: d.step.slice(0, 160).map((_, i) => i), y: d.step.slice(0, 160), step: true, color: 'var(--series-3)' }]} xLabel="n" yZero />}
            </Card>
          </div>
        </div>
      </div>
      <div className="grid grid-2">
        <Card
          title="Apply to the current signal"
          subtitle="Spectrum before and after filtering (Blackman window)"
          actions={
            <>
              <PlayButton id="dry" label="Original" get={() => playFiltered('dry')} />
              <PlayButton id="wet" label="Filtered" get={() => playFiltered('wet')} />
            </>
          }
        >
          {sig.data && applied?.sp && (
            <Plot height={260} series={[{ name: 'input', x: sig.data.spectrum.freq, y: sig.data.spectrum.db, color: 'var(--muted)' }, { name: 'output', x: applied.sp.freq, y: applied.sp.db }]} xLabel="frequency (Hz)" yLabel="dB" yDomain={[-140, 6]} />
          )}
          {applied && <DownloadButton small filename="filtered.csv" label="Filtered CSV" content={() => csvOf({ x: sig.data!.signal.x, y: applied.y })} />}
        </Card>
        <Card title="Fixed-point implementation" subtitle="Quantise coefficients (Q-format) and data; compare with double precision">
          <div className="grid grid-2" style={{ gap: 10 }}>
            <Slider label="Coefficient bits" value={coeffBits} min={4} max={24} step={1} onChange={(v) => setCoeffBits(Math.round(v))} format={(v) => v.toFixed(0)} />
            <Slider label="Data bits" value={dataBits} min={6} max={24} step={1} onChange={(v) => setDataBits(Math.round(v))} format={(v) => v.toFixed(0)} />
          </div>
          {fixed.data && (
            <>
              <Plot height={200} series={[{ name: 'double', x: fixed.data.freq, y: fixed.data.float_db, color: 'var(--muted)', width: 3 }, { name: `${coeffBits}-bit coefficients`, x: fixed.data.freq, y: fixed.data.fixed_db, dash: '5 3' }]} xLabel="frequency (Hz)" yLabel="dB" yDomain={[-140, 6]} />
              <div className="grid grid-2" style={{ gap: 12 }}>
                <div>
                  <KV k="Q format" v={`Q${fixed.data.b_q.int_bits}.${fixed.data.b_q.frac_bits}`} />
                  <KV k="Max coefficient error" v={fmtNum(fixed.data.b_q.max_error)} />
                  <KV k="Quantised filter" v={<StatusChip status={fixed.data.stable_fixed ? 'pass' : 'fail'} />} hint="stable after quantisation?" />
                </div>
                <div>
                  <KV k="Output SNR (fixed vs float)" v={`${fixed.data.output_snr_db.toFixed(1)} dB`} />
                  <KV k="Ideal data SNR 6.02·B + 1.76" v={`${fixed.data.theory_snr_db.toFixed(1)} dB`} />
                  <KV k="Max pole radius (fixed)" v={fixed.data.max_pole_radius_fixed ? fixed.data.max_pole_radius_fixed.toFixed(5) : '—'} />
                </div>
              </div>
            </>
          )}
        </Card>
      </div>
      <div className="grid grid-3">
        <Explainer title="Windowed-sinc & Kaiser FIR design" refs={[{ label: 'Oppenheim & Schafer §7.5–7.6' }, { label: 'J. F. Kaiser, "Nonrecursive digital filter design using the I0-sinh window function", Proc. IEEE ISCAS 1974' }]}>
          <Formula>{'h[n] = 2fc·sinc(2fc(n − M/2))·w[n]\nβ = 0.1102(A − 8.7)          (A > 50 dB)\nM = (A − 8) / (2.285·Δω)'}</Formula>
          A symmetric FIR has exactly linear phase: every frequency is delayed by (N−1)/2 samples (flat group delay). Kaiser's formulas turn
          a specification (A, Δf) straight into β and length.
        </Explainer>
        <Explainer title="Biquads & the bilinear transform" refs={[{ label: 'R. Bristow-Johnson, Audio EQ Cookbook (W3C)', href: 'https://www.w3.org/TR/audio-eq-cookbook/' }, { label: 'Oppenheim & Schafer §7.2' }]}>
          <Formula>{'s = 2fs·(1 − z⁻¹)/(1 + z⁻¹),   Ωc = 2fs·tan(π fc/fs)\nH(z) = (b0 + b1 z⁻¹ + b2 z⁻²)/(1 + a1 z⁻¹ + a2 z⁻²)'}</Formula>
          High-order IIR filters are built as cascades of second-order sections: each biquad's poles stay well-conditioned, which matters
          once coefficients are quantised. Try a 10th-order Butterworth at 50 Hz with 8-bit coefficients and watch the poles leave the circle.
        </Explainer>
        <Explainer title="Fixed point on the IRIS-DSP chip" refs={[{ label: 'B. Widrow & I. Kollár, Quantization Noise, Cambridge 2008' }]}>
          <Formula>{'SNR ≈ 6.02·B + 1.76 dB (full-scale sine)\nQ0.15: value = code / 2¹⁵'}</Formula>
          Each bit of data word length is worth ~6 dB. The Iris decimation FIR runs in hardware with <b>12-bit coefficients</b> and <b>16-bit</b> data —
          the Chip Lab turns the same coefficients into Verilog.
        </Explainer>
      </div>
    </div>
  );
}
