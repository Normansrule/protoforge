import { useMemo, useState } from 'react';
import { useCompute } from '../../engine/hooks';
import { tryCall } from '../../engine/engine';
import { Plot, fmtNum } from '../../components/Plot';
import { Card, DownloadButton, ErrorBox, Explainer, Formula, Select, Slider, StatusChip, Tabs, Toggle } from '../../components/ui';
import type { AnalyzeOut, FilterReport, FixedOut, SignalSpec, WindowKind } from './types';
import { WINDOW_LABEL } from './types';
import { PlayButton } from './SpectrumTab';
