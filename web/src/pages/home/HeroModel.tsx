// Live 3D model of the Iris glasses for the Overview hero. Lazy-loaded (three.js
// and the CAD viewer are a separate chunk) so the page paints before WebGL
// starts. Geometry comes straight from the Rust engine (`cad.parts`), so it
// follows every edit made in the CAD Studio.
import { Canvas, useFrame } from '@react-three/fiber';
import { ContactShadows, Environment, Lightformer, OrbitControls } from '@react-three/drei';
import { useEffect, useMemo, useRef, useState } from 'react';
import * as THREE from 'three';
import { useCompute } from '../../engine/hooks';
import { useProject } from '../../state/project';
import { PartEdges, PartMesh, useTheme, type MeshLike } from '../../labs/cad/viewer';
import { reducedMotion } from './motion';

interface PartsOut {
  parts: { name: string; label: string; color: string; mesh: MeshLike }[];
  display: { name: string; kind: string; color: string; opacity: number; mesh: MeshLike }[];
  total: { bbox_min: [number, number, number]; bbox_max: [number, number, number] };
}

function Spinner(props: { children: React.ReactNode; paused: boolean }) {
  const ref = useRef<THREE.Group>(null);
  const still = useMemo(reducedMotion, []);
  useFrame((_, dt) => {
    if (!ref.current || still || props.paused) return;
    ref.current.rotation.y += Math.min(dt, 0.05) * 0.32;
  });
  return (
    <group ref={ref} rotation={[0, still ? 0.35 : -0.5, 0]}>
      {props.children}
    </group>
  );
}

export default function HeroModel(props: { onReady?: () => void }) {
  const project = useProject((s) => s.project);
  const theme = useTheme();
  const { data } = useCompute<PartsOut>('cad.parts', { project, orientation: 'assembly', display: true });
  const host = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(true);
  const [dragging, setDragging] = useState(false);
  const finePointer = useMemo(() => !!window.matchMedia?.('(pointer: fine)').matches, []);

  useEffect(() => {
    if (data) props.onReady?.();
  }, [data]); // eslint-disable-line react-hooks/exhaustive-deps

  // Stop rendering when the hero scrolls out of view.
  useEffect(() => {
    const el = host.current;
    if (!el || typeof IntersectionObserver === 'undefined') return;
    const io = new IntersectionObserver((es) => setVisible(es.some((e) => e.isIntersecting)));
    io.observe(el);
    return () => io.disconnect();
  }, []);

  const geo = useMemo(() => {
    if (!data) return null;
    const { bbox_min: a, bbox_max: b } = data.total;
    const c: [number, number, number] = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2];
    const r = 0.5 * Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
    return { c, r, floor: -(b[2] - a[2]) / 2 };
  }, [data]);

  const edge = theme === 'light' ? '#1d2735' : '#dce6f5';
  const fov = 30;
  const dist = geo ? (geo.r / Math.sin(((fov / 2) * Math.PI) / 180)) * 1.08 : 400;
  const dir = new THREE.Vector3(0.15, 0.42, -1).normalize();

  return (
    <div ref={host} className="hm-model" aria-label="Rotating 3D model of the Iris smart-glasses frame, generated by the Rust engine" role="img">
      {data && geo && (
        <Canvas
          frameloop={visible ? 'always' : 'never'}
          camera={{ position: [dir.x * dist, dir.y * dist, dir.z * dist], fov, near: 1, far: 5000 }}
          dpr={[1, 2]}
          gl={{ antialias: true, alpha: true }}
          style={{ touchAction: finePointer ? 'none' : 'pan-y' }}
        >
          <ambientLight intensity={theme === 'light' ? 0.6 : 0.42} />
          <directionalLight position={[120, 220, -140]} intensity={1.35} />
          <directionalLight position={[-160, 90, 120]} intensity={0.5} />
          <Environment resolution={128} frames={1}>
            <Lightformer form="rect" intensity={2.2} position={[0, 4, -6]} scale={[10, 4, 1]} />
            <Lightformer form="rect" intensity={1.2} position={[-6, 2, 4]} scale={[6, 6, 1]} />
            <Lightformer form="ring" intensity={1.6} position={[6, 5, -2]} scale={3} />
            <Lightformer form="rect" intensity={0.6} color="#9ecbff" position={[0, -4, 0]} rotation-x={Math.PI / 2} scale={[20, 20, 1]} />
          </Environment>
          <group position={[0, geo ? -geo.r * 0.02 : 0, 0]}>
          <Spinner paused={dragging}>
            <group rotation={[-Math.PI / 2, 0, 0]}>
              <group position={[-geo.c[0], -geo.c[1], -geo.c[2]]}>
                {data.parts.map((p) => (
                  <group key={p.name}>
                    <PartMesh mesh={p.mesh} color={p.color} />
                    <PartEdges mesh={p.mesh} color={edge} opacity={0.22} />
                  </group>
                ))}
                {data.display.map((d) => (
                  <PartMesh key={d.name} mesh={d.mesh} color={d.color} opacity={d.opacity} roughness={0.1} clearcoat={1} renderOrder={2} />
                ))}
              </group>
            </group>
          </Spinner>
          </group>
          <ContactShadows position={[0, geo.floor - 2, 0]} scale={geo.r * 3} blur={2.6} opacity={theme === 'light' ? 0.3 : 0.5} far={geo.r * 1.4} resolution={512} frames={reducedMotion() ? 1 : Infinity} />
          {finePointer && (
            <OrbitControls
              enableZoom={false}
              enablePan={false}
              enableDamping
              minPolarAngle={Math.PI * 0.18}
              maxPolarAngle={Math.PI * 0.62}
              onStart={() => setDragging(true)}
              onEnd={() => setDragging(false)}
            />
          )}
        </Canvas>
      )}
    </div>
  );
}
